WRAP = Alignment(vertical='top', wrap_text=True)
WRAPC = Alignment(vertical='center', horizontal='center', wrap_text=True)


def _title(ws, text, sub=None, width=None):
    ws['A1'] = text
    ws['A1'].font = F_TITLE
    ws.row_dimensions[1].height = 22
    r = 2
    if sub:
        ws['A2'] = sub
        ws['A2'].font = F_LEAD
        ws['A2'].alignment = WRAP
        if width:
            ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=width)
        ws.row_dimensions[2].height = 30
        r = 3
    return r + 1


def _section(ws, row, text):
    ws.cell(row=row, column=1, value=text).font = F_SEC
    return row + 1


def _table(ws, row, headers, widths, rows, fills=None):
    """見出し行＋データ行を書き、次の書き込み行を返す。

    fills: 行ごとの塗り色（None or 長さ=len(rows) のリスト）
    """
    for i, (h, w) in enumerate(zip(headers, widths), start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font, c.alignment, c.border = F_HEAD, WRAPC, BOX
        c.fill = PatternFill('solid', fgColor=C_HEAD)
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[row].height = 30
    ws.freeze_panes = ws.cell(row=row + 1, column=1)
    for j, data in enumerate(rows):
        rr = row + 1 + j
        color = (fills[j] if fills else None) or (C_BAND if j % 2 else None)
        for i, v in enumerate(data, start=1):
            c = ws.cell(row=rr, column=i, value=v)
            c.font, c.alignment, c.border = F_BODY, WRAP, BOX
            if color:
                c.fill = PatternFill('solid', fgColor=color)
    return row + 1 + len(rows) + 1


def _notes(ws, row, lines, width=1):
    for t in lines:
        c = ws.cell(row=row, column=1, value=t)
        c.font = F_BODY if not t.startswith('■') else F_BOLD
        c.alignment = WRAP
        if width > 1:
            ws.merge_cells(start_row=row, start_column=1,
                           end_row=row, end_column=width)
        row += 1
    return row + 1


