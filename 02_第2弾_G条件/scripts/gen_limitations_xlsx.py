def main():
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    src = os.path.join(BASE, 'scripts', '_limitations_measured.json')
    if not os.path.exists(src):
        print('先に scripts/measure_limitations.py を実行してください。')
        return 1
    m = json.load(io.open(src, encoding='utf-8'))

    wb = Workbook()
    wb.remove(wb.active)
    sheet_intro(wb, m)
    sheet_kinds(wb, m)
    sheet_reasons(wb, m)
    sheet_options(wb, m)
    sheet_scope(wb, m)
    for ws in wb.worksheets:
        ws.sheet_view.showGridLines = False

    outdir = os.path.join(BASE, '資料')
    if not os.path.isdir(outdir):
        os.makedirs(outdir)
    out = os.path.join(
        outdir,
        'G条件表・テストケースに出ないもの（制限事項と切り分けガイド）_v%s.xlsx'
        % APP_VERSION)
    wb.save(out)
    print('作成: %s' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
