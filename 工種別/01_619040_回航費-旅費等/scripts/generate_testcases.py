"""
テストケース生成: 01_619040 回航費-旅費等
チケット: #619040  工種ID: 6439-667
変更内容: 日当(旅行諸雑費) R~Syo=200円/日 を計算表・代価表(行13-15)に追加
フローパターン: A（テーブル行追加のみ・フロー変化なし）
"""
import csv
import io

# ============================================================
# 変更定義
# ============================================================
KODATE_NICCHOW = 200.0  # 日当(旅行諸雑費) 新版固定値 [円/日]

HEADERS = [
    'テストID', 'テスト区分',
    '宿泊区分', '片道往復区分', '宿泊日数(SYU)',
    '期待：日当単価(R~Syo)[円/日]',
    '期待：代価表13-15行目',
    '確認観点',
]

# ============================================================
# テストケース定義
# 宿泊区分 C: 1=宿泊あり / 0=日帰り
# 片道往復 k: 1=片道     / 2=往復
# ============================================================
cases = [
    # (tc_no, 区分,  宿泊区分ラベル, C, 片道往復ラベル, k, SYU, 代価表確認,           確認観点)
    (1, '差分', '宿泊あり(C=1)', 1, '片道(k=1)', 1, 1,
     '計上される（船団長・高級船員・普通船員 各1行）',
     '日当単価=200円/日。数量は各人数×(SYU+C)×k の計算式通りか'),
    (2, '差分', '宿泊あり(C=1)', 1, '往復(k=2)', 2, 1,
     '計上される（3行）、数量はTC-001の2倍',
     '往復(k=2)で日当数量がTC-001の2倍になっているか'),
    (3, '差分', '日帰り(C=0)', 0, '片道(k=1)', 1, 0,
     '数量=0（計上なし）',
     '宿泊なし・SYU=0 のとき日当が計上されないか'),
    (4, '回帰', '宿泊あり(C=1)', 1, '片道(k=1)', 1, 1,
     '行1-12（宿泊費・宿泊手当等）に変化なし',
     '既存の宿泊費(D4-D9行)・宿泊手当(D7T)の計算結果が旧版と同じか'),
]

rows = [HEADERS]
for tc_no, kubun, syu_lbl, c, katamichi_lbl, k, syu, daika_expect, kanten in cases:
    niccho = KODATE_NICCHOW if c == 1 or syu > 0 else ''
    rows.append([
        f'TC-{tc_no:03d}',
        kubun,
        syu_lbl,
        katamichi_lbl,
        str(syu),
        str(niccho) if niccho != '' else '計上なし',
        daika_expect,
        kanten,
    ])

# ============================================================
# CSV出力（Shift-JIS）
# ============================================================
out_path = (
    r'C:\Users\imoo\Desktop\ClaudeCode\14.歩掛Jsonからテストケース作成可能か'
    r'\工種別\01_619040_回航費-旅費等\output'
    r'\テストケース仕様書_6439-667_回航費-旅費等_2026.csv'
)

buf = io.StringIO()
writer = csv.writer(buf, lineterminator='\r\n')
for row in rows:
    writer.writerow(row)
csv_text = buf.getvalue()

with open(out_path, 'w', encoding='cp932', newline='') as f:
    f.write(csv_text)

print(f'生成完了: {len(cases)}件')
print()
print(csv_text)
